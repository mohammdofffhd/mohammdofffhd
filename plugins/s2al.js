const games = {};


module.exports = {
  command: "سؤال",
  description: "أسئلة أنمي 🎌",


  async execute(sock, msg) {

    const chat = msg.key.remoteJid;


    if (games[chat]) {
      return sock.sendMessage(chat,{
        text:"❌ يوجد سؤال جاري الآن"
      },{quoted:msg});
    }


    const q = questions[Math.floor(Math.random()*questions.length)];


    games[chat] = q;


    await sock.sendMessage(chat,{
      text:
`🎌 *سؤال أنمي*

❓ ${q[0]}

⏳ جاوب بسرعة`
    },{quoted:msg});


    setTimeout(()=>{
      if(games[chat]){
        delete games[chat];
        sock.sendMessage(chat,{
          text:"⌛ انتهى وقت السؤال"
        });
      }
    },30000);

  },


  async onMessage(sock,msg){

    const chat = msg.key.remoteJid;

    if(!games[chat]) return;


    const answer =
    msg.message?.conversation?.trim();


    if(!answer) return;


    if(answer.toLowerCase() === games[chat][1].toLowerCase()){

      await sock.sendMessage(chat,{
        text:"✅ إجابة صحيحة 🎉"
      },{quoted:msg});

      delete games[chat];

    } else {

      await sock.sendMessage(chat,{
        text:"❌ إجابة غلط"
      },{quoted:msg});

    }

  }
};